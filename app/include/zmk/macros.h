#pragma once

#include <stddef.h>
#include <stdint.h>
#include <zmk/behavior.h>

/**
 * @brief Accessors used by the Studio "macros" RPC subsystem (see
 *        app/src/studio/macro_subsystem.c) to enumerate and edit the macro behaviors
 *        (`zmk,behavior-macro` and its one/two-param variants) configured on the device, without
 *        exposing the internal `struct behavior_macro_config` layout from behavior_macro.c.
 *
 * A macro's compiled form is just a flat array of behavior bindings (control steps like
 * &macro_tap or &macro_pause_for_release are bindings to special behaviors), so listing/editing
 * steps is expressed entirely in terms of `struct zmk_behavior_binding`. The per-instance
 * config storage generated by the devicetree macros in behavior_macro.c is mutable RAM
 * (non-const statics) that the runtime reads on every invocation, so edits take effect
 * immediately; the setters below also recompute the macro's precalculated release state (which
 * depends on where &macro_pause_for_release sits in the step list). The number of steps is
 * fixed by the devicetree; adding/removing steps or whole macros is out of scope, and nothing
 * is persisted across reboots yet (mirroring the combos subsystem's current milestones).
 */

/** @brief Number of macro instances configured in the devicetree (all three compat variants). */
size_t zmk_macros_get_count(void);

/**
 * @return The behavior device name for the macro at `index` (its DT label property if set,
 *         otherwise the node name), or NULL if `index` is out of range.
 */
const char *zmk_macros_get_name(size_t index);

/** @return The macro's default wait-ms, or -EINVAL if `index` is out of range. */
int32_t zmk_macros_get_wait_ms(size_t index);

/** @return The macro's default tap-ms, or -EINVAL if `index` is out of range. */
int32_t zmk_macros_get_tap_ms(size_t index);

/**
 * @brief Get a pointer to the macro's step bindings array, along with its length.
 * @return Pointer to the bindings, with `*len_out` set to the number of entries. NULL (with
 *         `*len_out` set to 0) if `index` is out of range.
 */
const struct zmk_behavior_binding *zmk_macros_get_bindings(size_t index, size_t *len_out);

/**
 * @brief Update an existing macro's default wait/tap timing. Takes effect immediately.
 * @return 0 on success, -EINVAL if `index` is out of range.
 */
int zmk_macros_set_timing(size_t index, uint32_t wait_ms, uint32_t tap_ms);

/**
 * @brief Replace a single step of the macro. Takes effect immediately and recomputes the
 *        macro's release state. `binding.behavior_dev` must remain valid for the lifetime of
 *        the device (pass a name returned by zmk_behavior_find_behavior_name_from_local_id()).
 * @return 0 on success, -EINVAL if `index` is out of range, -ERANGE if `binding_index` is out
 *         of range for this macro.
 */
int zmk_macros_set_binding(size_t index, size_t binding_index,
                           struct zmk_behavior_binding binding);

/*
 * chibiboard FW45 (2026-10-01): macro control steps (&macro_wait_time, &macro_tap_time,
 * &macro_tap/press/release, &macro_pause_for_release) are not real behavior devices, so they
 * have no behavior local id (zmk_behavior_get_local_id() returns UINT16_MAX). Without an id the
 * Studio app could never write a wait-time step back, and a saved control step was lost after
 * a reboot. Each control step gets a fixed pseudo id instead (0xFFF0..0xFFF5).
 */
#define ZMK_MACRO_CONTROL_PSEUDO_ID_NONE UINT16_MAX

/** @return the pseudo id for a control step name, or ZMK_MACRO_CONTROL_PSEUDO_ID_NONE. */
uint16_t zmk_macros_control_pseudo_id(const char *behavior_name);

/** @return the control step name for a pseudo id (a static string), or NULL. */
const char *zmk_macros_control_name_for_pseudo_id(uint32_t id);

/**
 * @brief Delete every persisted macro edit and restore the live configs to the stock
 *        (devicetree) values, in place. Used by the Studio "Restore Stock Settings" RPC.
 * @return 0 on success.
 */
int zmk_macros_reset_settings(void);
